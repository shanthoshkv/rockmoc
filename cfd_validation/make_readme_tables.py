"""validation/data/{summary,all_checks}.csv -> docs/validation_cfd.md and README per-case table.

    py -3.12 cfd_validation/make_readme_tables.py
"""
import csv
from collections import defaultdict
from pathlib import Path

R = Path(__file__).resolve().parent.parent
D = R / "validation" / "data"
S = list(csv.DictReader(open(D / "summary.csv")))
C = list(csv.DictReader(open(D / "all_checks.csv")))


def f(v, nd=2, pct=False):
    try:
        x = float(v)
    except ValueError:
        return "–"
    if x != x:
        return "–"
    return f"{x:+.{nd}f}" if pct else f"{x:.{nd}f}"


def case_table():
    h = ("| case | tier | description | Isp rockmoc [s] | Isp CFD [s] | Isp err [%] | tol [%] | exit M (CFD) | Cd CFD | Cd rockmoc "
         "| axis M rms | field M rms | gated pass/fail |\n|---|---|---|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|\n")
    rows = []
    for r in S:
        rows.append(f"| `{r['case']}` | {r['tier']} | {r['title']} | {f(r['Isp_rockmoc_s'])} | {f(r['Isp_cfd_s'])} | "
                    f"{f(r['Isp_err_pct'], 3, True)} | {f(r['Isp_tol_pct'], 1)} | {f(r['exit_M_cfd'], 3)} | {f(r['Cd_cfd'], 4)} | "
                    f"{f(r['Cd_rockmoc'], 4)} | {f(r['axis_M_rms'], 4)} | {f(r['field_M_rms'], 4)} | {r['gated_pass']}/{r['gated_fail']} |")
    return h + "\n".join(rows) + "\n"


def g(v):
    try:
        return f"{float(v):.5g}"
    except ValueError:
        return v


def checks_md():
    by = defaultdict(list)
    for c in C:
        by[c["case"]].append(c)
    out = []
    for r in S:
        cs = by[r["case"]]
        out.append(f"<details><summary><code>{r['case']}</code>: {r['title']} ({r['gated_pass']} pass, {r['gated_fail']} fail, "
                   f"{len(cs)} rows)</summary>\n\n| quantity | rockmoc | CFD | error | tolerance | status | note |\n|---|--:|--:|--:|--:|---|---|")
        for c in cs:
            out.append(f"| {c['quantity']} | {g(c['rockmoc'])} | {g(c['cfd'])} | {g(c['relative'] if c['relative'] else c['error'])} | "
                       f"{g(c['tolerance'])} | {c['status']} | {c['note']} |")
        out.append("\n</details>\n")
    return "\n".join(out)


if __name__ == "__main__":
    n = {k: sum(c["status"] == k for c in C) for k in ("PASS", "FAIL", "info")}
    head = (f"# rockmoc vs OpenFOAM: every case, every check\n\nGenerated by `cfd_validation/make_readme_tables.py` from "
            f"`validation/data/all_checks.csv` ({n['PASS']} PASS, {n['FAIL']} FAIL, {n['info']} informational).\n\n"
            "Sign: Isp error = CFD / rockmoc − 1. For error-type checks (rms, max) the rockmoc column is 0 and the CFD column holds the error.\n\n"
            "## Per-case summary\n\n" + case_table() + "\n## All checks\n\n" + checks_md())
    (R / "docs" / "validation_cfd.md").write_text(head, encoding="utf-8")
    (R / "docs" / "images" / "cfd_case_table.md").write_text(case_table(), encoding="utf-8")
    print(n)
